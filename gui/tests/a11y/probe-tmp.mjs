import { chromium } from 'playwright';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const axeSource = fs.readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8');
const root = process.argv[2]; const shots = process.argv[3];
const srv = http.createServer((q, r) => { let p = path.join(root, q.url === '/' ? 'index.html' : q.url.split('?')[0]); if (!fs.existsSync(p)) p = path.join(root,'index.html'); const t = p.endsWith('.wasm')?'application/wasm':p.endsWith('.js')?'text/javascript':p.endsWith('.css')?'text/css':'text/html'; r.writeHead(200,{'content-type':t}); r.end(fs.readFileSync(p)); }).listen(0);
const url = `http://127.0.0.1:${srv.address().port}/`;
const b = await chromium.launch(); const page = await (await b.newContext({viewport:{width:1280,height:900}})).newPage();
page.on('console', m => m.type() !== 'warning' && console.log('console', m.type(), m.text().slice(0,300)));
page.on('pageerror', e => console.log('pageerror', e.message.slice(0,300)));
const t0 = Date.now();
await page.goto(url); await page.waitForSelector('#start-heading');
console.log('start screen ready in', Date.now() - t0, 'ms');
await page.getByRole('button', { name: 'I understand' }).click();
await page.getByRole('button', { name: 'Choose a sample file…' }).click();
await page.waitForSelector('#overview-heading');
await page.getByRole('button', { name: 'Change settings first' }).click();
await page.waitForTimeout(1500);
console.log('focused:', await page.evaluate(() => document.activeElement?.id), 'title:', await page.title());
await page.screenshot({ path: shots + '/settings-1.png', fullPage: true });
await page.addScriptTag({ content: axeSource });
const res = await page.evaluate(async () => axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa','best-practice'] } }));
for (const v of res.violations) console.log('axe', v.id, v.help, v.nodes.slice(0,3).map(n => n.target.join(' ')).join(' | '));
console.log('fields:', await page.locator('#settings-panel-forms input, #settings-panel-forms select, #settings-panel-forms textarea').count());
await b.close(); srv.close();
